export interface BlueprintPin {
  id: string
  name: string
  friendlyName: string
  direction: 'input' | 'output'
  type: { category: string; subcategory: string; object: string; container: string; [key: string]: unknown }
  defaultValue: string
  autogeneratedDefault: string
  defaultObject: string
  defaultText: string
  flags: number
  links: Array<{ node?: string; nodeName?: string; pin: string; export?: number }>
  [key: string]: unknown
}
export interface BlueprintNode {
  id: string
  exportIndex: number
  name: string
  classPath: string
  title: string
  x: number
  y: number
  width: number
  height: number
  comment: string
  complete: boolean
  opaqueProperties?: string[]
  properties: Record<string, unknown>
  pins: BlueprintPin[]
}
export interface BlueprintGraph {
  kind?: 'event' | 'pose' | 'state-machine' | 'transition'
  schema?: string
  id: string
  name: string
  path: string
  complete: boolean
  diagnostics: string[]
  nodes: BlueprintNode[]
}
export interface BlueprintDocument {
  schemaVersion: 1
  readerVersion?: number
  assetClass?: string
  status: 'complete' | 'partial' | 'unsupported'
  engineVersion: string
  graphs: BlueprintGraph[]
  diagnostics: string[]
  assetReview?: UnrealAssetDocument
}
export interface UnrealAssetObject {
  references?: Array<{ propertyPath: string; target: string; className: string }>
  sourcePackage?: string
  serializedPath?: string
  id: string
  path: string
  name: string
  classPath: string
  outer: string
  properties: Record<string, unknown>
  decoded: boolean
  opaqueProperties?: string[]
  opaqueBytes: number
  opaqueHash: string
  diagnostics: string[]
}
export interface UnrealAssetDocument {
  family: 'map' | 'mesh' | 'statetree' | 'animation' | 'blueprint' | 'texture' | 'animation-sequence' | 'asset'
  objects: UnrealAssetObject[]
  coverage: string[]
  cooked: boolean
}
export interface BlueprintSide {
  geometry?: NativeMeshGeometry
  resolvedRef?: string
  ref: string
  path: string
  status: 'ready' | 'absent' | 'unavailable'
  reason?: string
  sourceBytes?: number
  contentHash?: string
  documentKey?: string
  document?: BlueprintDocument
}
export interface BlueprintRequest {
  nativeGeometry?: boolean
  externalActors?: boolean
  knownDocuments?: string[]
  force?: boolean
  filePath: string
  oldPath?: string
  leftRef: string
  rightRef: string
  requestId: string
}
export interface NativeMeshGeometry {
  status: 'ready' | 'unavailable'
  provider: 'unreal-source-mesh-v1'
  engineVersion: string
  reason?: string
  diagnostics: string[]
  totalLods: number
  lods: Array<{ index: number; vertexCount: number; triangleCount: number; vertices: [number, number, number][]; indices: number[]; reason?: string }>
}
export interface ExternalActorPackage { left: BlueprintSide; right: BlueprintSide }
export interface ExternalActorReview {
  scope: 'changed-packages'
  total: number
  omitted: number
  packages: ExternalActorPackage[]
  diagnostics: string[]
}
export interface BlueprintComparison {
  left: BlueprintSide; right: BlueprintSide
  externalActors?: ExternalActorReview
  owningMaps?: { left?: string; right?: string }
}
