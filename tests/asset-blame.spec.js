const { test, expect } = require('@playwright/test')
const fs = require('node:fs'), path = require('node:path'), http = require('node:http')
const { DIST, git, tmpDir, cleanup } = require('./helpers')
const root = path.resolve(__dirname, '..')
test.afterAll(cleanup)

test('asset blame follows real Git renames and excludes later commits at an older revision', async () => {
  const { gitService } = require(path.join(DIST, 'services/GitService'))
  const repo = tmpDir('lg-asset-blame-git-')
  git(repo, 'init', '-q'); git(repo, 'config', 'user.name', 'Asset Author'); git(repo, 'config', 'user.email', 'asset@example.com')
  fs.writeFileSync(path.join(repo, 'Old.umap'), Buffer.from([0, 1, 2, 3]))
  git(repo, 'add', '.'); git(repo, 'commit', '-qm', 'Create map')
  git(repo, 'mv', 'Old.umap', 'Map.umap'); git(repo, 'commit', '-qm', 'Rename map')
  const revision = git(repo, 'rev-parse', 'HEAD').trim()
  fs.writeFileSync(path.join(repo, 'Map.umap'), Buffer.from([0, 4, 5, 6]))
  git(repo, 'add', '.'); git(repo, 'commit', '-qm', 'Later map edit')
  const entries = await gitService.log(repo, { filePath: 'Map.umap', refs: [revision], limit: 100 })
  expect(entries.map(entry => entry.message)).toEqual(['Rename map', 'Create map'])
  expect(entries[0].author).toBe('Asset Author')
})

test('Blame tab loads on demand, handles revisions, retries and stale responses at narrow width', async ({ page }) => {
  const dir = tmpDir('lg-asset-blame-ui-')
  const doc = { graphs: [], status: 'unsupported', diagnostics: [], assetClass: '/Script/Engine.World', assetReview: { family: 'map', objects: [], coverage: [], cooked: false } }
  await require('esbuild').build({ stdin: { contents: `import React from 'react';import {createRoot} from 'react-dom/client';import {UnrealAssetReview} from './src/components/diff/UnrealAssetReview';import './src/index.css';const root=createRoot(document.getElementById('root'));window.show=(filePath='Map.umap',leftRef='base',rightRef='selected')=>root.render(<UnrealAssetReview repoPath="repo" request={{filePath,oldPath:'Old.umap',leftRef,rightRef}}/>);window.show();`, resolveDir: root, loader: 'tsx' }, alias: { '@': path.join(root, 'src') }, outfile: path.join(dir, 'app.js'), bundle: true, format: 'esm' })
  const server = http.createServer((req, res) => {
    if (req.url === '/') {
      res.setHeader('Content-Type', 'text/html')
      return res.end(`<html><link rel="stylesheet" href="/app.css"><style>html,body,#root{margin:0;width:100%;height:100%;display:flex}</style><div id="root"></div><script>
        window.reads=[];window.compareReads=0;window.fail=false;window.delay=false;
        window.lucidGit={logRendererEvent:async()=>{},blueprintCompare:async()=>{window.compareReads++;return {left:{status:'ready',ref:'base',document:${JSON.stringify(doc)}},right:{status:'ready',ref:'selected',document:${JSON.stringify(doc)}}}},blueprintCancel:async()=>{},
        log:async(repo,args)=>{window.reads.push(args);if(window.fail)throw Error('Offline object');if(window.delay)return await new Promise(resolve=>window.finish=()=>resolve([{hash:'delayed',author:'Stale Author',timestamp:1000,message:'Stale history'}]));return args.refs[0]==='empty'?[]:[{hash:'abcdef0123456789',author:args.refs[0]==='base'?'Base Author':'Selected Author',timestamp:1000,message:'Changed the map'}]}};
      </script><script type="module" src="/app.js"></script></html>`)
    }
    res.setHeader('Content-Type', req.url.endsWith('.css') ? 'text/css' : 'text/javascript')
    res.end(fs.readFileSync(path.join(dir, req.url.slice(1))))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  try {
    await page.setViewportSize({ width: 350, height: 800 })
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await expect(page.getByText('Reading saved asset revisions…')).toHaveCount(0)
    expect(await page.evaluate(() => window.reads)).toEqual([])
    const tab = page.getByRole('button', { name: 'Blame', exact: true })
    await tab.focus(); await page.keyboard.press('Enter')
    const blame = page.getByRole('region', { name: 'Asset blame' })
    await expect(tab).toHaveAttribute('aria-pressed', 'true')
    await expect(blame).toContainText('Selected Author')
    expect(await page.evaluate(() => window.reads)).toEqual([{filePath:'Map.umap',refs:['selected'],limit:100}])
    await page.getByRole('button', { name: 'Contents', exact: true }).click()
    await tab.click(); await expect(blame).toContainText('Selected Author')
    expect(await page.evaluate(() => window.reads.length)).toBe(1)
    await page.getByRole('button', { name: 'Base', exact: true }).click()
    await expect(blame).toContainText('Base Author')
    expect(await page.evaluate(() => window.reads.at(-1))).toEqual({filePath:'Old.umap',refs:['base'],limit:100})
    await page.evaluate(() => { window.fail=true })
    await page.getByRole('button', { name: 'Selected', exact: true }).click()
    await expect(blame.getByRole('alert')).toContainText('Offline object')
    await page.evaluate(() => { window.fail=false })
    await page.getByRole('button', { name: 'Retry blame' }).click()
    await expect(blame).toContainText('Selected Author')
    await page.evaluate(() => { window.delay=true })
    await page.getByRole('button', { name: 'Base', exact: true }).click()
    await expect(blame.getByRole('status')).toContainText('Loading blame')
    await page.evaluate(() => { window.delay=false })
    await page.getByRole('button', { name: 'Selected', exact: true }).click()
    await page.evaluate(() => window.finish())
    await expect(blame).toContainText('Selected Author'); await expect(blame).not.toContainText('Stale Author')
    expect(await page.evaluate(() => window.compareReads)).toBe(1)
    expect(await tab.evaluate(el => el.getBoundingClientRect().right <= innerWidth)).toBe(true)
    fs.mkdirSync(path.join(root, 'audit/evidence/asset-blame'), {recursive:true})
    await page.screenshot({ path: path.join(root, 'audit/evidence/asset-blame/blame-narrow.png') })
    await page.evaluate(() => window.show('Map.umap','base','ABSENT'))
    await tab.click(); await page.getByRole('button', {name:'Selected',exact:true}).click()
    await expect(blame).toContainText('File absent in this revision')
    await page.evaluate(() => window.show('Map.umap','base','empty'))
    await tab.click(); await expect(blame).toContainText('No committed history')
    await page.evaluate(() => window.show('Map.umap','base','WORKING'))
    await tab.click(); await expect(blame).toContainText('Local changes have no commit author yet')
    expect(await page.evaluate(() => window.reads.at(-1).refs)).toEqual(['HEAD'])
    expect(errors).toEqual([])
  } finally { await page.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)) }
})
